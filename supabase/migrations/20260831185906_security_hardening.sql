-- A signed-in user may change only their display name. Identity, role, and
-- account-control fields are service-only even if a future grant is widened by
-- mistake; the trigger provides a second independent enforcement layer.
CREATE OR REPLACE FUNCTION public.guard_profiles_role()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
BEGIN
  IF auth.uid() IS NOT NULL AND (
    NEW.id IS DISTINCT FROM OLD.id
    OR NEW.email IS DISTINCT FROM OLD.email
    OR NEW.role IS DISTINCT FROM OLD.role
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
    OR NEW.disabled_at IS DISTINCT FROM OLD.disabled_at
    OR NEW.disabled_by IS DISTINCT FROM OLD.disabled_by
  ) THEN
    RAISE EXCEPTION 'protected_profile_field';
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.guard_profiles_role()
  FROM PUBLIC, anon, authenticated, service_role;

