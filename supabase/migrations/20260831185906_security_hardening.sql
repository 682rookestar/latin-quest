-- Cryptographically generate class codes. 32 symbols divide 256 evenly, so
-- selecting each byte modulo 32 introduces no distribution bias.
CREATE OR REPLACE FUNCTION public.generate_join_code()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  candidate text;
  bytes bytea;
  attempt integer := 0;
  i integer;
BEGIN
  LOOP
    bytes := extensions.gen_random_bytes(10);
    candidate := '';
    FOR i IN 0..9 LOOP
      candidate := candidate || substr(alphabet, (get_byte(bytes, i) % 32) + 1, 1);
    END LOOP;

    IF NOT EXISTS (SELECT 1 FROM public.classes WHERE join_code = candidate) THEN
      RETURN candidate;
    END IF;

    attempt := attempt + 1;
    IF attempt > 20 THEN
      RAISE EXCEPTION 'Could not allocate a unique join code';
    END IF;
  END LOOP;
END;
$function$;

REVOKE ALL ON FUNCTION public.generate_join_code()
  FROM PUBLIC, anon, authenticated, service_role;

-- Durable, per-pupil throttling for answer checks and final submissions. The
-- table is private and the public wrapper is callable only by the service role.
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS private.exercise_rate_limit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  action text NOT NULL CHECK (action IN ('check', 'submit')),
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS exercise_rate_limit_events_lookup_idx
  ON private.exercise_rate_limit_events (student_id, action, occurred_at DESC);

ALTER TABLE private.exercise_rate_limit_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE private.exercise_rate_limit_events
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE private.exercise_rate_limit_events_id_seq
  FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.consume_exercise_rate_limit(
  p_student uuid,
  p_action text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, private
AS $function$
DECLARE
  v_limit integer;
  v_count integer;
BEGIN
  IF p_student IS NULL OR p_action NOT IN ('check', 'submit') THEN
    RETURN false;
  END IF;

  v_limit := CASE p_action WHEN 'check' THEN 60 ELSE 12 END;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_student::text || ':' || p_action, 0));

  DELETE FROM private.exercise_rate_limit_events
   WHERE student_id = p_student
     AND occurred_at < now() - interval '1 day';

  SELECT count(*)
    INTO v_count
    FROM private.exercise_rate_limit_events
   WHERE student_id = p_student
     AND action = p_action
     AND occurred_at >= now() - interval '1 minute';

  IF v_count >= v_limit THEN
    RETURN false;
  END IF;

  INSERT INTO private.exercise_rate_limit_events (student_id, action)
  VALUES (p_student, p_action);
  RETURN true;
END;
$function$;

REVOKE ALL ON FUNCTION public.consume_exercise_rate_limit(uuid, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_exercise_rate_limit(uuid, text)
  TO service_role;

